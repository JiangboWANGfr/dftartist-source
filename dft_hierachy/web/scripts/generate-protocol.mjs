// Dev-time only. The committed outputs run without a schema compiler or eval.
import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { createHash } from "node:crypto";
import { compile } from "json-schema-to-typescript";
import Ajv2020 from "ajv/dist/2020.js";
import standaloneCode from "ajv/dist/standalone/index.js";
import addFormats from "ajv-formats";
import { _Code } from "ajv/dist/compile/codegen/code.js";
import { build } from "esbuild";

const web = new URL("../", import.meta.url);
const source = await readFile(new URL("../protocol/schema/hier.schema.json", web), "utf8");
const schema = JSON.parse(source);
const hash = createHash("sha256").update(source).digest("hex");
const header = `// Generated by web/scripts/generate-protocol.mjs. DO NOT EDIT.\n// Source: protocol/schema/hier.schema.json; SHA-256 ${hash}\n`;
const nameOf = (ref) => ref.$ref.split("/").at(-1);
// The schema deliberately uses conditional constraints without local type keywords.
// Python's independent Draft202012Validator also checks the source schema in CI.
const ajv = new Ajv2020({
  strict: false,
  allErrors: false,
  inlineRefs: false,
  code: { source: true, esm: true },
  validateFormats: true,
});
addFormats(ajv, { mode: "full" });
// The contract uses Gregorian UTC milliseconds (also B's datetime oracle), not
// RFC3339 leap-second strings or ISO astronomical year zero. Embed this same
// predicate in standalone output; there is no runtime compiler/eval.
function utcCalendar(value) {
  const date = new Date(value);
  return (
    !value.startsWith("0000-") && Number.isFinite(date.getTime()) && date.toISOString() === value
  );
}
ajv.addFormat("date-time", { type: "string", validate: utcCalendar });
ajv.opts.code.formats = new _Code(
  `{...require("ajv-formats/dist/formats").fullFormats,"date-time":{validate:${utcCalendar.toString()}}}`,
);
ajv.addSchema(schema);
const exports = Object.fromEntries(
  Object.keys(schema.$defs).map((name) => [name, `${schema.$id}#/$defs/${name}`]),
);
const standalone = standaloneCode(ajv, exports);
const bundled = await build({
  stdin: { contents: standalone, resolveDir: fileURLToPath(web), loader: "js" },
  bundle: true,
  platform: "browser",
  format: "esm",
  write: false,
  legalComments: "inline",
});
const notices = await Promise.all(
  ["ajv/LICENSE", "ajv-formats/LICENSE"].map((p) =>
    readFile(new URL(`node_modules/${p}`, web), "utf8"),
  ),
);
// A property for every definition keeps aliases and otherwise unreachable method
// params in the generated type graph, including definitions collapsed by $ref.
const typeRoot = {
  $defs: schema.$defs,
  type: "object",
  additionalProperties: false,
  properties: Object.fromEntries(
    Object.keys(schema.$defs).map((n) => [n, { $ref: `#/$defs/${n}` }]),
  ),
  required: Object.keys(schema.$defs),
};
let types = await compile(typeRoot, "WireDefinitions", {
  bannerComment: header,
  style: { singleQuote: false },
});
const declared = new Set([...types.matchAll(/export (?:type|interface) (\w+)/g)].map((m) => m[1]));
types += Object.keys(schema.$defs)
  .filter((n) => !declared.has(n))
  .map((n) => `export type ${n} = WireDefinitions[${JSON.stringify(n)}];\n`)
  .join("");
const methods = Object.fromEntries(
  Object.entries(schema["x-hier-methods"]).map(([method, entry]) => [
    method,
    {
      ...entry,
      params: nameOf(entry.params),
      result: nameOf(entry.result),
      response: nameOf(entry.response),
    },
  ]),
);
// Keep only the schema information needed to canonicalize outbound parameters.
function descriptor(s) {
  const local = Object.fromEntries(
    Object.entries(s).flatMap(([k, v]) => {
      if (["default", "type"].includes(k)) return [[k, v]];
      if (k === "properties")
        return [[k, Object.fromEntries(Object.entries(v).map(([n, d]) => [n, descriptor(d)]))]];
      if (k === "items") return [[k, descriptor(v)]];
      return [];
    }),
  );
  return s.$ref ? mergeDescriptor(descriptor(schema.$defs[nameOf(s)]), local) : local;
}
function mergeDescriptor(base, local) {
  const merged = { ...base, ...local };
  if (base.properties || local.properties) {
    merged.properties = { ...base.properties };
    for (const [key, value] of Object.entries(local.properties ?? {}))
      merged.properties[key] = mergeDescriptor(merged.properties[key] ?? {}, value);
  }
  if (base.items && local.items) merged.items = mergeDescriptor(base.items, local.items);
  return merged;
}
// Canonicalization only needs the present params vocabulary. Fail generation if
// a future schema introduces branching defaults rather than silently dropping them.
const visitedParams = new Set();
function checkParams(s) {
  if (["allOf", "anyOf", "oneOf"].some((k) => k in s))
    throw new Error("Parameter canonicalization needs support for union/intersection shapes");
  // Existing if/then only constrain values of already declared fields. Defaults
  // or references inside branches require an explicit generator extension.
  for (const key of ["if", "then", "else"])
    if (s[key] && /"(?:default|\$ref|type)"\s*:/.test(JSON.stringify(s[key])))
      throw new Error("Parameter canonicalization needs support for conditional shapes/defaults");
  if (s.$ref && !visitedParams.has(s.$ref)) {
    visitedParams.add(s.$ref);
    checkParams(schema.$defs[nameOf(s)]);
  }
  for (const value of Object.values(s.properties ?? {})) checkParams(value);
  if (s.items) checkParams(s.items);
}
for (const method of Object.values(schema["x-hier-methods"])) checkParams(method.params);
const registry =
  header +
  'import type * as Wire from "./wire.generated.js";\n' +
  `export const PROTOCOL_VERSION = ${schema.$defs[nameOf(schema["x-hier-contract"].protocolVersion)].const} as const;\n` +
  `export const SCHEMA_VERSION = ${schema.$defs[nameOf(schema["x-hier-contract"].schemaVersion)].const} as const;\n` +
  `export const METHODS = ${JSON.stringify(methods, null, 2)} as const;\n` +
  "export interface MethodMap {\n" +
  Object.entries(methods)
    .map(
      ([m, e]) => `  ${JSON.stringify(m)}: { params: Wire.${e.params}; result: Wire.${e.result} };`,
    )
    .join("\n") +
  "\n}\n" +
  `export const PARAM_DESCRIPTORS = ${JSON.stringify(
    Object.fromEntries(
      [...visitedParams].map((ref) => {
        const name = nameOf({ $ref: ref });
        return [name, descriptor(schema.$defs[name])];
      }),
    ),
  )};\n`;
const outputs = new Map([
  ["wire.generated.ts", types],
  ["registry.generated.ts", registry],
  ["validators.generated.js", header + bundled.outputFiles[0].text],
  ["validators.LICENSE.txt", notices.join("\n---\n")],
]);
let mismatches = 0;
for (const [name, contents] of outputs) {
  const path = new URL(`packages/protocol-types/src/${name}`, web);
  if (process.argv.includes("--check")) {
    const old = await readFile(path, "utf8").catch(() => undefined);
    if (old !== contents) {
      console.error(`Generated file differs: ${name}`);
      mismatches++;
    }
  } else await writeFile(path, contents);
}
console.log(
  `${process.argv.includes("--check") ? "Checked" : "Generated"} ${Object.keys(exports).length} definitions / ${Object.keys(methods).length} methods; schema ${hash}`,
);
if (mismatches) process.exitCode = 1;
